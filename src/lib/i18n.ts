export function getLocalizedField(
  obj: Record<string, unknown>,
  field: string,
  lang: Language
): string {
  if (lang === 'hi') {
    const hiKey = `${field}_hi`;
    const val = obj[hiKey] as string | null;
    if (val && val.trim()) return val;
  }
  if (lang === 'mr') {
    const mrKey = `${field}_mr`;
    const val = obj[mrKey] as string | null;
    if (val && val.trim()) return val;
  }
  return (obj[field] as string) || '';
}

